"""A smaller config made from the real one: some modes, their tables and language packs, a few rows changed.

    python -m hebzip.ops.config_subset --modes fast --out site/py/browser.toml \\
        --set engine='"python"' --set table_store='"eager"' --set fallback='[]'

Why (the website): the browser build runs mode ``fast`` only, in Pyodide - no numba, no mapped
copy, no fallback codecs (their libraries are not there). It used to be a hand-trimmed copy of the config,
which drifts the day a row of ``fast`` changes. This makes it FROM the real config every time:

* text level, no TOML writer - every kept section is copied as written (comments included), so the rows
  of a kept mode cannot differ from the real ones;
* kept = the preamble, ``[hebzip]`` (with the ``--set`` rows replaced - a row that does not exist is
  refused), ``[tables.<t>]`` + its sub-sections for every table the modes read (``mode_tables``, derived
  from the drawer rows), ``[languages.<l>]`` of the modes, ``[modes.<m>]`` + its sub-sections;
* proof before writing: the result loads (every row checked as at start-up) and every kept mode's format
  signature equals the real config's (``select.pinned_signature``) - so the packages are the same bytes.
A ``[hebzip]`` row given with ``--set`` must sit on one line in the real config. This is a tool: it reports
to stdout directly.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from hebzip.config.load import DEFAULT_CONFIG, load_config, load_dict
from hebzip.config.schema import Settings
from hebzip.config.tables import mode_tables
from hebzip.core.errors import ConfigError, HebzipError
from hebzip.core.files import write_bytes_atomic
from hebzip.services.select import pinned_signature

HEADER = re.compile(r"^\[([A-Za-z0-9_.]+)\]\s*(#.*)?$")
"""A section header at the start of a line (hebzip.toml has no arrays of tables)."""
GENERATED = ("# GENERATED by `python -m hebzip.ops.config_subset` from config/hebzip.toml - do not edit by hand;\n"
             "# change the real config (or the --set rows of the build) and generate again.\n")


@dataclass(frozen=True)
class Section:
    """One ``[name]`` and its lines as written (the header line first; '' = the preamble)."""

    name: str
    lines: tuple[str, ...]


def split_sections(text: str) -> list[Section]:
    """The config text as sections. Comment and blank lines right before a header belong to that header."""
    sections: list[Section] = []
    name, lines = "", []
    for line in text.splitlines(keepends=True):
        match = HEADER.match(line)
        if match is None:
            lines.append(line)
            continue
        cut = len(lines)
        while cut > 0 and (not lines[cut - 1].strip() or lines[cut - 1].lstrip().startswith("#")):
            cut -= 1
        sections.append(Section(name, tuple(lines[:cut])))
        name, lines = match.group(1), [*lines[cut:], line]
    sections.append(Section(name, tuple(lines)))
    return sections


def wanted(settings: Settings, modes: list[str]) -> set[str]:
    """Every section name the subset keeps (sub-sections are kept with their parent, ``_kept``)."""
    for mode in modes:
        if mode not in settings.modes:
            raise ConfigError(f"config_subset: no such mode '{mode}'")
    names = {"", "hebzip"} | {f"modes.{m}" for m in modes}
    names |= {f"tables.{t}" for m in modes for t in mode_tables(settings, m)}
    names |= {f"languages.{settings.modes[m].language}" for m in modes if settings.modes[m].language}
    return names


def _kept(name: str, keep: set[str]) -> bool:
    return any(name == k or name.startswith(k + ".") for k in keep if k)


def _set_rows(section: Section, rows: dict[str, str]) -> Section:
    """``[hebzip]`` with each ``row = value`` replaced (value = a TOML literal); an unknown row is refused."""
    lines = list(section.lines)
    for row, value in rows.items():
        tomllib.loads(f"x = {value}")
        hits = [i for i, line in enumerate(lines) if re.match(rf"^{re.escape(row)}\s*=", line)]
        if len(hits) != 1:
            raise ConfigError(f"config_subset: [hebzip].{row} must be one row of the real config")
        lines[hits[0]] = f"{row} = {value}  # set by the build\n"
    return Section(section.name, tuple(lines))


def subset_text(text: str, settings: Settings, modes: list[str], rows: dict[str, str]) -> str:
    """The subset config as text (``settings`` = the real config parsed from ``text``)."""
    keep = wanted(settings, modes)
    out = [GENERATED]
    for section in split_sections(text):
        if section.name == "hebzip":
            section = _set_rows(section, rows)
        if section.name == "" or _kept(section.name, keep):
            out.extend(section.lines)
    return "".join(out)


def proven(text: str, real: Settings, modes: list[str]) -> Settings:
    """Load the subset and prove every kept mode signs exactly like the real config."""
    small = load_dict(tomllib.loads(text), "config_subset")
    for mode in modes:
        if pinned_signature(small, mode) != pinned_signature(real, mode):
            raise ConfigError(f"config_subset: mode {mode} would sign differently - refused")
    return small


def make(config: Path, modes: list[str], rows: dict[str, str]) -> str:
    """The proven subset text of ``config``."""
    text = config.read_text(encoding="utf-8-sig")
    real = load_config(config)
    small = subset_text(text, real, modes, rows)
    proven(small, real, modes)
    return small


def _rows(pairs: list[str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for pair in pairs:
        row, sep, value = pair.partition("=")
        if not sep or not row.strip():
            raise ConfigError(f"config_subset: --set wants row=value, got '{pair}'")
        out[row.strip()] = value.strip()
    return out


def main(argv: Sequence[str] | None = None) -> int:
    """CLI: 0 = the subset was proven and written; the error's exit code otherwise."""
    parser = argparse.ArgumentParser(prog="hebzip.ops.config_subset")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--modes", required=True, help="comma-separated mode names")
    parser.add_argument("--set", action="append", default=[], help="[hebzip] row=TOML value (repeatable)")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        text = make(args.config, [m for m in args.modes.split(",") if m], _rows(args.set))
    except (HebzipError, tomllib.TOMLDecodeError) as error:
        sys.stderr.write(f"{error}\n")
        return getattr(error, "exit_code", 2)
    write_bytes_atomic(args.out, text.encode("utf-8"))
    sys.stdout.write(f"written: {args.out.name} ({len(text.encode('utf-8'))} bytes, modes {args.modes})\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
